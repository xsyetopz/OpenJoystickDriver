/// Xbox One S Bluetooth report layout with share and the d-pad button bits never set, and Guide
/// mirrored into report 2; the format behind the 045E:02FD `hid-xbox-one-s-bt` profile.
public struct XboxGeckoHIDReportFormat: VirtualGamepadReportFormat {
  private let base: HIDDescriptorReportFormat

  public var descriptor: [UInt8] { base.descriptor }
  public var inputReportPayloadSize: Int { base.inputReportPayloadSize }
  public var inputReportID: UInt8? { base.inputReportID }
  public var outputReportPayloadSize: Int? { base.outputReportPayloadSize }
  public var outputReportID: UInt8? { base.outputReportID }

  public init() throws {
    base = try HIDDescriptorReportFormat(
      descriptor: XboxOneBluetoothHIDDescriptor.oneSDescriptor,
      outputReportID: ConsumerOutputCodec.xboxOneReportID,
      outputReportPayloadSize: ConsumerOutputCodec.xboxOneReportPayloadSize,
      buttonUsageMap: XboxOneBluetoothHIDDescriptor.buttonUsageMap
    )
  }

  public func buildInputReport(from state: VirtualGamepadState) -> [UInt8] {
    var state = state
    let unavailableButtons: UInt32 =
      (0xF << 11) | (1 << UInt32(GamepadHIDDescriptor.ButtonBit.share.rawValue))
    state.buttons &= ~unavailableButtons
    return base.buildInputReport(from: state)
  }

  /// Report 2 carries Guide alone (usage 0x85, one bit), the only Guide source SDL reads for the
  /// 16-byte packet.
  public func buildAuxiliaryInputReports(from state: VirtualGamepadState) -> [[UInt8]] {
    let guide = GamepadHIDDescriptor.ButtonBit.guide.rawValue
    return [[Self.guideReportID, state.buttons & (1 << UInt32(guide)) != 0 ? 1 : 0]]
  }

  private static let guideReportID: UInt8 = 2
}

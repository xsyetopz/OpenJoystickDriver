public struct DualSenseUSBHIDReportFormat: VirtualGamepadReportFormat {
  public let descriptor: [UInt8] = DualSenseUSBHIDDescriptor.descriptor
  public let inputReportPayloadSize: Int = DualSenseUSBHIDDescriptor.inputReportLength - 1
  public let inputReportID: UInt8? = DualSenseUSBHIDDescriptor.reportID
  public let outputReportPayloadSize: Int? = DualSenseUSBHIDDescriptor.outputReportLength - 1
  public let outputReportID: UInt8? = DualSenseUSBHIDDescriptor.outputReportID

  public init() {}

  public func buildInputReport(from state: VirtualGamepadState) -> [UInt8] {
    var report = [UInt8](repeating: 0, count: DualSenseUSBHIDDescriptor.inputReportLength)
    report[0] = DualSenseUSBHIDDescriptor.reportID
    report[1] = SonyHIDAxis.uint8(state.leftStickX)
    report[2] = SonyHIDAxis.uint8Inverted(state.leftStickY)
    report[3] = SonyHIDAxis.uint8(state.rightStickX)
    report[4] = SonyHIDAxis.uint8Inverted(state.rightStickY)
    report[5] = SonyHIDAxis.triggerByte(state.effectiveLeftTrigger)
    report[6] = SonyHIDAxis.triggerByte(state.effectiveRightTrigger)
    report[8] = SonyHIDAxis.ds4Hat(state.hat) | SonyHIDAxis.ds4Face(state.buttons)
    report[9] = SonyHIDAxis.ds4Shoulders(
      state.buttons,
      leftTrigger: state.effectiveLeftTrigger,
      rightTrigger: state.effectiveRightTrigger
    )
    if SonyHIDAxis.isSet(state.buttons, bit: GamepadHIDDescriptor.ButtonBit.guide.rawValue) {
      report[10] |= 0x01
    }
    if state.touchpadPressed { report[10] |= 0x02 }
    if state.mutePressed { report[10] |= 0x04 }
    // Only the touchpad button is modeled; both touch contacts are inactive.
    report[33] = 0x80
    report[37] = 0x80
    return report
  }
}
